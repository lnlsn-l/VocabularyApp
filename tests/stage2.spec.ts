test('第二阶段中文 composition 和选词结束 Enter 不误提交，正常 Enter 保留', async ({ page }) => {
  await page.goto('./')
  await page.getByRole('button', { name: '＋ 添加词条', exact: true }).click()
  const word = page.getByLabel('英文词汇 / 短语')
  await word.fill('substrate'); await page.getByLabel('中文释义').fill('衬底')
  await word.focus()
  await word.dispatchEvent('compositionstart', { data: '衬' })
  await page.keyboard.press('Enter')
  await expect(page.getByRole('dialog')).toBeVisible()
  await expect(page.getByRole('article')).toHaveCount(0)
  await word.evaluate(element => {
    element.dispatchEvent(new CompositionEvent('compositionend', { bubbles: true, data: '衬底' }))
    const enter = new KeyboardEvent('keydown', { key: 'Enter', isComposing: false, bubbles: true, cancelable: true })
    element.dispatchEvent(enter)
    if (!enter.defaultPrevented) throw new Error('选词尾部 Enter 未被保护')
    element.closest('form')!.requestSubmit()
  })
  await expect(page.getByRole('article')).toHaveCount(0)
  await page.waitForTimeout(120)
  await page.keyboard.press('Enter')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page.getByRole('article')).toHaveCount(1)
  const search = page.getByRole('searchbox')
  await search.fill('衬底')
  await search.dispatchEvent('compositionstart', { data: '衬底' })
  await page.keyboard.press('Enter')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page.getByRole('article')).toContainText('查看 0 次')
  await search.dispatchEvent('compositionend', { data: '衬底' })
})

