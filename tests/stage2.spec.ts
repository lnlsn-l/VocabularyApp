test('第二阶段真实 v1 升级、应用命名空间和其他应用数据保留', async ({ page, baseURL }) => {
  await page.goto(new URL('favicon.svg', baseURL!).href)
  const legacy = await page.evaluate(async () => {
    const open = (name: string, version: number, upgrade: (db: IDBDatabase) => void) => new Promise<IDBDatabase>((resolve, reject) => {
      const request = indexedDB.open(name, version)
      request.onupgradeneeded = () => upgrade(request.result)
      request.onsuccess = () => resolve(request.result); request.onerror = () => reject(request.error)
    })
    const other = await open('OtherApp.test', 1, db => db.createObjectStore('settings'))
    const otherTx = other.transaction('settings', 'readwrite')
    otherTx.objectStore('settings').put('keep-me', 'sentinel')
    await new Promise<void>(resolve => { otherTx.oncomplete = () => resolve() }); other.close()
    localStorage.setItem('OtherApp.settings', 'keep-me')
    sessionStorage.setItem('OtherApp.session', 'keep-me')
    const db = await open('VocabularyDB', 1, db => {
      const table = db.createObjectStore('vocabulary', { keyPath: 'id' })
      table.createIndex('normalizedWord', 'normalizedWord', { unique: true })
      for (const key of ['status', 'createdAt', 'lastSearchedAt']) table.createIndex(key, key)
    })
    const row = { id: 'legacy-browser', word: 'substrate', meaning: '旧词库释义', note: '旧备注', status: 'learning', normalizedWord: 'substrate',
      searchCount: 7, createdAt: '2025-01-01T00:00:00.000Z', updatedAt: '2025-02-02T00:00:00.000Z', lastSearchedAt: '2026-10-01T00:00:00.000Z' }
    const transaction = db.transaction('vocabulary', 'readwrite')
    transaction.objectStore('vocabulary').add(row)
    await new Promise<void>((resolve, reject) => { transaction.oncomplete = () => resolve(); transaction.onerror = () => reject(transaction.error) })
    db.close(); return row
  })
  await page.goto(baseURL!)
  await expect(page.getByRole('article', { name: 'substrate', exact: true })).toContainText('旧词库释义')
  const migrated = await state(page)
  expect(migrated.entries).toEqual([legacy])
  expect(migrated.metadata).toEqual([expect.objectContaining({ key: 'VocabularyApp.backupState', dataRevision: 1, lastExportedRevision: 0 })])
  const exported = await backup(page)
  expect(exported.entries[0]).toMatchObject({ id: legacy.id, searchCount: 7, note: '旧备注', updatedAt: legacy.updatedAt })
  const untouched = await page.evaluate(async () => {
    const request = indexedDB.open('OtherApp.test')
    const db = await new Promise<IDBDatabase>(resolve => { request.onsuccess = () => resolve(request.result) })
    const read = db.transaction('settings', 'readonly').objectStore('settings').get('sentinel')
    const value = await new Promise<unknown>(resolve => { read.onsuccess = () => resolve(read.result) }); db.close()
    return { value, local: localStorage.getItem('OtherApp.settings'), session: sessionStorage.getItem('OtherApp.session'),
      localNames: Object.keys(localStorage), sessionNames: Object.keys(sessionStorage) }
  })
  expect(untouched).toEqual({ value: 'keep-me', local: 'keep-me', session: 'keep-me', localNames: ['OtherApp.settings'], sessionNames: ['OtherApp.session'] })
})

