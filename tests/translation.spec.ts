test('翻译错误恢复：无结果、超时、离线、HTTP/业务/429/额度/配置/异常 JSON，输入与 revision 保留', async ({ page }) => {
  expectedFailures.add(page)
  await open(page); const before = await state(page)
  await page.getByLabel('中文释义').fill('手写'); await page.getByLabel('备注').fill('笔记')
  const cases = [
    [404, 'no_results', '没有取得翻译参考'], [504, 'timeout', '翻译请求超时'], [429, 'rate_limited', '查询过于频繁'],
    [429, 'quota_exceeded', '翻译额度暂不足'], [503, 'not_configured', '翻译服务暂不可用'], [502, 'upstream_failure', '翻译服务返回异常'],
  ] as const
  for (const [status, code, message] of cases) {
    await page.route(endpoint, route => route.fulfill({ status, json: { error: { code } } }))
    await page.getByRole('button', { name: '获取翻译参考', exact: true }).click()
    await expect(page.getByRole('dialog')).toContainText(message)
    await expect(page.getByLabel('中文释义')).toHaveValue('手写'); await expect(page.getByLabel('备注')).toHaveValue('笔记')
    await page.unroute(endpoint)
  }
  await page.route(endpoint, route => route.fulfill({ body: '{', contentType: 'application/json' }))
  await page.getByRole('button', { name: '获取翻译参考', exact: true }).click(); await expect(page.getByRole('dialog')).toContainText('翻译服务返回异常')
  await page.unroute(endpoint)
  await page.route(endpoint, route => route.abort('internetdisconnected'))
  await page.getByRole('button', { name: '获取翻译参考', exact: true }).click(); await expect(page.getByRole('dialog')).toContainText('网络连接失败')
  expect(await state(page)).toEqual(before)
  await page.unroute(endpoint)
  await page.getByRole('button', { name: '获取翻译参考', exact: true }).click(); await expect(page.getByRole('button', { name: '采用此翻译', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '保存', exact: true }).click(); await expect(page.getByRole('article')).toContainText('手写')
})
