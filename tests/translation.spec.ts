import { expect, test, type Page, type Route } from '@playwright/test'
import { readFile } from 'node:fs/promises'
const endpoint = 'http://127.0.0.1:8788/translate'
const browserErrors = new WeakMap<Page, string[]>()
const expectedFailures = new WeakSet<Page>()
test.beforeEach(({ page }) => {
  const errors: string[] = []; browserErrors.set(page, errors)
  page.on('pageerror', error => errors.push(error.message))
  page.on('console', message => {
    if (message.type() === 'error' && !(expectedFailures.has(page) && message.location().url === endpoint
      && /^Failed to load resource:/.test(message.text()))) errors.push(message.text())
  })
})
test.afterEach(({ page }) => { expect(browserErrors.get(page)).toEqual([]) })
async function state(page: Page) {
  return page.evaluate(async () => {
    const opening = indexedDB.open('VocabularyDB')
    const db = await new Promise<IDBDatabase>((resolve, reject) => { opening.onsuccess = () => resolve(opening.result); opening.onerror = () => reject(opening.error) })
    try {
      const tx = db.transaction(['vocabulary', 'vocabularyAppMetadata'], 'readonly')
      const read = (store: string) => new Promise<unknown[]>((resolve, reject) => {
        const request = tx.objectStore(store).getAll(); request.onsuccess = () => resolve(request.result); request.onerror = () => reject(request.error)
      })
      return { entries: await read('vocabulary'), metadata: await read('vocabularyAppMetadata') }
    } finally { db.close() }
  })
}
async function open(page: Page, word = 'fixture') {
  await page.goto('./'); await page.getByRole('button', { name: '＋ 添加词条' }).click()
  await page.getByLabel('英文词汇 / 短语').fill(word)
}
async function candidate(route: Route, text: string) {
  return route.fulfill({ json: { query: route.request().postDataJSON().query, source: 'youdao', translations: [text] } })
}
